import os
import uuid
import datetime
import logging
from agents.base import BaseAgentAdapter
from core.schemas import Task, AgentRun, AgentStatus, AgentResult

logger = logging.getLogger("orchestrator.agents.mock")


class MockAgentAdapter(BaseAgentAdapter):
    """Deterministic Mock Adapter for automated orchestrator verification and testing."""

    def __init__(self, simulate_failure: bool = False):
        self.simulate_failure = simulate_failure
        self._runs = {}

    async def start_task(self, task: Task, worktree_path: str) -> AgentRun:
        run_id = f"run-mock-{uuid.uuid4().hex[:8]}"
        run = AgentRun(
            run_id=run_id,
            task_id=task.id,
            agent_type="mock_agent",
            worktree_path=worktree_path,
            status=AgentStatus.RUNNING,
        )

        # Synthesize target files in worktree for verification
        for filepath in task.target_files:
            full_path = os.path.join(worktree_path, filepath)
            os.makedirs(os.path.dirname(full_path), exist_ok=True)
            with open(full_path, "w", encoding="utf-8") as f:
                f.write(f'"""Synthesized code generated by MockAgent for task {task.id}."""\n')
                f.write(f"def task_{task.id.replace('-', '_')}_func():\n")
                f.write(f'    return "Success for role {task.role.value}"\n')

        self._runs[run_id] = {
            "run": run,
            "task": task,
            "logs": [
                f"[{datetime.datetime.now(datetime.timezone.utc).isoformat()}] MockAgent generated synthesized target files."
            ],
        }
        return run

    async def poll(self, run: AgentRun) -> AgentStatus:
        run_data = self._runs.get(run.run_id)
        if not run_data:
            return AgentStatus.FAILED
        status = AgentStatus.FAILED if self.simulate_failure else AgentStatus.COMPLETED
        run_data["run"].status = status
        return status

    async def get_result(self, run: AgentRun) -> AgentResult:
        run_data = self._runs.get(run.run_id, {})
        task = run_data.get("task")
        success = not self.simulate_failure
        return AgentResult(
            run_id=run.run_id,
            task_id=run.task_id,
            success=success,
            modified_files=task.target_files if task else [],
            output_summary="Mock execution finished successfully." if success else "Mock execution failed gate check.",
        )
